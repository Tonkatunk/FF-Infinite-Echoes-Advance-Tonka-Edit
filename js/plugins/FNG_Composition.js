Game_Party.prototype.getItemRecipe = function(item){
    const allRecipe = this.compositionRecipe();
    var iType;
    if(DataManager.isWeapon(item)){
        iType = "W";
    }else if(DataManager.isArmor(item)){
        iType = "A";
    }else if(DataManager.isItem(item)){
        iType = "I";
    }
    for(recipe of allRecipe){
        if(recipe[0] == iType && item.id == recipe[1]){
            return recipe;
        }
    }
    return [];
}

Game_Party.prototype.getIncludeRecipeItems = function(item){
    const allRecipe = this.compositionRecipe();
    var iType;
    var goods = [];
    if(DataManager.isWeapon(item)){
        iType = "W";
    }else if(DataManager.isArmor(item)){
        iType = "A";
    }else if(DataManager.isItem(item)){
        iType = "I";
    }
    for(recipe of allRecipe){
        for(let i=2;i<recipe.length;i++){
            if(recipe[i][0] == iType && item.id == recipe[i][1]){
                switch(recipe[0]){
                    case "W":
                        goods.push($dataWeapons[recipe[1]]);
                        break;
                    case "A":
                        goods.push($dataArmors[recipe[1]]);
                        break;
                    case "I":
                        goods.push($dataItems[recipe[1]]);
                        break;
                }
            }
        }
    }
    return goods;
}

Game_Party.prototype.isComposibleItem = function(item){
    const recipe = this.getItemRecipe(item);
    
    for(let i=2;i<recipe.length;i++){
        const num = recipe[i][2];
        var material;
        if(recipe[i][0] == "I"){
            material = $dataItems[recipe[i][1]];
        }else if(recipe[i][0] == "W"){
            material = $dataWeapons[recipe[i][1]];
        }else if(recipe[i][0] == "A"){
            material = $dataArmors[recipe[i][1]];
        }
        if($gameParty.numItems(material)<num){
            return false;
        }
    }
    return true;    
}

