Window_Materials.prototype.setItem = function(item) {
    this.contents.clear();
    this.changeTextColor(ColorManager.systemColor());
    this.drawText("Synthesis Material",0,0,this.innnerWidth);
    const recipe = $gameParty.getItemRecipe(item);
    for(let i=2;i<recipe.length;i++){
        var info = recipe[i];
        var material;
        if(info[0] == "I"){
            material = $dataItems[info[1]];
        }else if(info[0] == "W"){
            material = $dataWeapons[info[1]];
        }else if(info[0] == "A"){
            material = $dataArmors[info[1]];
        }
        this.changePaintOpacity($gameParty.numItems(material)>=info[2]);
        this.drawItemName(material,0,$TILE/2*(i-1),this.innerWidth);
        this.changePaintOpacity(true);
        this.drawText($gameParty.numItems(material)+"/"+info[2],0,$TILE/2*(i-1),this.innerWidth,"right");
    }
};